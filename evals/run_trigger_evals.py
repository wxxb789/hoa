#!/usr/bin/env python3
"""Offline validation for the trigger (routing) eval suite.

trigger-cases.json is graded by an LLM judge in a fresh context (see its
procedure); this script validates its structure AND cross-checks every case's
must_pick / distractors against the real artifact catalog generated by
scripts/generate_index.py — a case routing to a nonexistent artifact fails
here, in CI, instead of silently in a judge run.

It also validates a recorded evals/baseline.json when one exists: every case id
exists, the pass count equals the sum of per-case passes, and the record
describes the full current case set. No baseline is allowed before the first
explicit `judge_trigger_evals.py --record` run. Nothing here uses the network.

Run: python evals/run_trigger_evals.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

EVALS = Path(__file__).resolve().parent
ROOT = EVALS.parent
sys.path.insert(0, str(ROOT / "scripts"))

import generate_index as gi  # noqa: E402

REQUIRED_TOP = {"purpose", "procedure", "cases"}
REQUIRED_CASE = {"id", "request", "must_pick", "distractors"}
BASELINE = EVALS / "baseline.json"
BASELINE_FIELDS = ("case_count", "model", "effort", "passed", "total",
                   "judge_endpoint_host", "generated_at", "per_case")


def _catalog_names() -> set[str]:
    """Artifact names from the real catalog (skills + library folders)."""
    return {row["name"] for row in gi.collect()}


def _is_int(value) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def load_baseline(path=None) -> dict | None:
    """The recorded baseline, or None when no record exists yet."""
    target = BASELINE if path is None else Path(path)
    if not target.exists():
        return None
    try:
        record = json.loads(target.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"baseline.json: unreadable: {error}") from error
    if not isinstance(record, dict):
        raise ValueError("baseline.json: expected a JSON object")
    return record


def baseline_errors(cases: list[dict], record: dict) -> list[str]:
    """Every way a recorded baseline disagrees with the current case set."""
    errors: list[str] = []
    missing = [field for field in BASELINE_FIELDS if field not in record]
    if missing:
        return [f"baseline.json: missing keys: {missing}"]

    for key in ("model", "effort", "judge_endpoint_host", "generated_at"):
        value = record[key]
        if not isinstance(value, str) or not value.strip():
            errors.append(f"baseline.json: {key} must be a non-empty string")

    case_ids = {case["id"] for case in cases}
    per_case = record["per_case"]
    if not isinstance(per_case, list):
        errors.append("baseline.json: per_case must be a list")
        per_case = []
    seen: set[str] = set()
    passed_rows = 0
    for index, entry in enumerate(per_case):
        where = f"baseline.json: per_case[{index}]"
        if not isinstance(entry, dict):
            errors.append(f"{where} must be an object")
            continue
        missing = [key for key in ("id", "pick", "passed") if key not in entry]
        if missing:
            errors.append(f"{where} missing keys: {missing}")
            continue
        if not isinstance(entry["id"], str) or not entry["id"]:
            errors.append(f"{where} id must be a non-empty string")
        elif entry["id"] not in case_ids:
            errors.append(f"{where} id {entry['id']!r} is not in trigger-cases.json")
        elif entry["id"] in seen:
            errors.append(f"{where} duplicate id {entry['id']!r}")
        else:
            seen.add(entry["id"])
        if not isinstance(entry["pick"], str):
            errors.append(f"{where} pick must be a string")
        if not isinstance(entry["passed"], bool):
            errors.append(f"{where} passed must be a boolean")
        elif entry["passed"]:
            passed_rows += 1

    case_count = record["case_count"]
    passed = record["passed"]
    total = record["total"]
    for key, value in (("case_count", case_count), ("passed", passed), ("total", total)):
        if not _is_int(value):
            errors.append(f"baseline.json: {key} must be an integer")
    if _is_int(case_count) and case_count != len(cases):
        errors.append(f"baseline.json: case_count {case_count} != current case count "
                      f"{len(cases)}; re-record the baseline")
    if _is_int(case_count) and len(per_case) != case_count:
        errors.append(f"baseline.json: per_case has {len(per_case)} rows, "
                      f"case_count is {case_count}")
    if _is_int(total) and _is_int(case_count) and total != case_count:
        errors.append(f"baseline.json: total {total} != case_count {case_count}")
    if _is_int(passed) and passed != passed_rows:
        errors.append(f"baseline.json: passed {passed} != sum(per_case.passed) "
                      f"{passed_rows}")
    if _is_int(passed) and _is_int(total) and not 0 <= passed <= total:
        errors.append(f"baseline.json: passed {passed} is outside 0..{total}")
    return errors


def main() -> int:
    try:
        data = json.loads((EVALS / "trigger-cases.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"run_trigger_evals: unreadable trigger-cases.json: {exc}", file=sys.stderr)
        return 1

    errors: list[str] = []
    missing = REQUIRED_TOP - data.keys()
    if missing:
        print(f"run_trigger_evals: missing top-level keys: {sorted(missing)}", file=sys.stderr)
        return 1
    if not isinstance(data["cases"], list) or not data["cases"]:
        print("run_trigger_evals: cases must be a non-empty list", file=sys.stderr)
        return 1

    catalog = _catalog_names()
    seen_ids: set[str] = set()
    for i, case in enumerate(data["cases"]):
        where = f"case[{i}]"
        missing = REQUIRED_CASE - case.keys()
        if missing:
            errors.append(f"{where}: missing keys: {sorted(missing)}")
            continue
        cid = case["id"]
        if cid in seen_ids:
            errors.append(f"{where}: duplicate id {cid!r}")
        seen_ids.add(cid)
        if not isinstance(case["request"], str) or not case["request"].strip():
            errors.append(f"{where} ({cid}): request must be a non-empty string")
        must_pick = case["must_pick"]
        if not (isinstance(must_pick, list) and len(must_pick) == 1
                and isinstance(must_pick[0], str) and must_pick[0].strip()):
            errors.append(f"{where} ({cid}): must_pick must be a list of exactly one artifact name")
        distractors = case["distractors"]
        if (not isinstance(distractors, list) or not distractors
                or not all(isinstance(v, str) and v.strip() for v in distractors)):
            errors.append(f"{where} ({cid}): distractors must be a non-empty list of names")
        else:
            unknown = [v for v in distractors if v not in catalog]
            if unknown:
                errors.append(f"{where} ({cid}): distractors name unknown artifacts: {unknown}")
        if isinstance(must_pick, list) and len(must_pick) == 1 and must_pick[0] in catalog \
                and isinstance(distractors, list):
            if must_pick[0] in distractors:
                errors.append(f"{where} ({cid}): must_pick {must_pick[0]!r} is also a distractor")

    if errors:
        for error in errors:
            print(f"run_trigger_evals: {error}", file=sys.stderr)
        return 1

    try:
        record = load_baseline()
    except ValueError as error:
        print(f"run_trigger_evals: {error}", file=sys.stderr)
        return 1
    if record is not None:
        errors = baseline_errors(data["cases"], record)
        if errors:
            for error in errors:
                print(f"run_trigger_evals: {error}", file=sys.stderr)
            return 1
        baseline = (f"; baseline consistent ({record['passed']}/{record['total']} passed, "
                    f"model {record['model']}, {record['generated_at']})")
    else:
        baseline = "; no baseline recorded yet (judge_trigger_evals.py --record)"

    print(f"PASS: {len(data['cases'])} trigger cases valid; every must_pick/distractor "
          f"resolves to a cataloged artifact ({len(catalog)} artifacts){baseline}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
