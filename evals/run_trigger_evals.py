#!/usr/bin/env python3
"""Offline validation for the trigger (routing) eval suite.

trigger-cases.json is graded by an LLM judge in a fresh context (see its
procedure); this script validates its structure AND cross-checks every case's
must_pick / distractors against the real artifact catalog generated by
scripts/generate_index.py — a case routing to a nonexistent artifact fails
here, in CI, instead of silently in a judge run.

Run: python evals/run_trigger_evals.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

EVALS = Path(__file__).resolve().parent
ROOT = EVALS.parent
sys.path.insert(0, str(ROOT / "scripts"))

import generate_index as gi  # noqa: E402

REQUIRED_TOP = {"purpose", "procedure", "cases"}
REQUIRED_CASE = {"id", "request", "must_pick", "distractors"}


def _catalog_names() -> set[str]:
    """Artifact names from the real catalog (skills + library folders)."""
    return {row["name"] for row in gi.collect()}


def main() -> int:
    try:
        data = json.loads((EVALS / "trigger-cases.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"run_trigger_evals: unreadable trigger-cases.json: {exc}", file=sys.stderr)
        return 1

    errors: list[str] = []
    missing = REQUIRED_TOP - data.keys()
    if missing:
        print(f"run_trigger_evals: missing top-level keys: {sorted(missing)}", file=sys.stderr)
        return 1
    if not isinstance(data["cases"], list) or not data["cases"]:
        print("run_trigger_evals: cases must be a non-empty list", file=sys.stderr)
        return 1

    catalog = _catalog_names()
    seen_ids: set[str] = set()
    for i, case in enumerate(data["cases"]):
        where = f"case[{i}]"
        missing = REQUIRED_CASE - case.keys()
        if missing:
            errors.append(f"{where}: missing keys: {sorted(missing)}")
            continue
        cid = case["id"]
        if cid in seen_ids:
            errors.append(f"{where}: duplicate id {cid!r}")
        seen_ids.add(cid)
        if not isinstance(case["request"], str) or not case["request"].strip():
            errors.append(f"{where} ({cid}): request must be a non-empty string")
        for field in ("must_pick", "distractors"):
            value = case[field]
            if (not isinstance(value, list) or not value
                    or not all(isinstance(v, str) and v.strip() for v in value)):
                errors.append(f"{where} ({cid}): {field} must be a non-empty list of names")
                continue
            unknown = [v for v in value if v not in catalog]
            if unknown:
                errors.append(f"{where} ({cid}): {field} names unknown artifacts: {unknown}")
        overlap = set(case.get("must_pick", [])) & set(case.get("distractors", []))
        if overlap:
            errors.append(f"{where} ({cid}): same artifact in must_pick and distractors: {sorted(overlap)}")

    if errors:
        for error in errors:
            print(f"run_trigger_evals: {error}", file=sys.stderr)
        return 1
    print(f"PASS: {len(data['cases'])} trigger cases valid; every must_pick/distractor "
          f"resolves to a cataloged artifact ({len(catalog)} artifacts)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
